"""
Abstract base class and data schemas for Energy Management System (EMS) strategies.
Designed following the Strategy Pattern to enable seamless swapping between:
- Baseline Rule-Based EMS
- Equivalent Consumption Minimization Strategy (ECMS / A-ECMS)
- Predictive Machine Learning / Deep Reinforcement Learning (DDPG / PPO / SAC) models.
"""

from abc import ABC, abstractmethod
from dataclasses import dataclass
from typing import Dict, Any, Optional
from models.vehicle import VehicleConfig


@dataclass
class EMSInput:
    """Standardized input state fed to any EMS controller at time step t."""
    time_s: float
    speed_kmh: float
    speed_ms: float
    acceleration_ms2: float
    p_demand_kw: float
    soc: float
    distance_km: float


@dataclass
class EMSOutput:
    """Standardized decision output generated by any EMS controller."""
    p_ice_kw: float           # ICE power command [kW] (0 to 100 kW)
    p_em_kw: float            # Electric motor power command [kW] (-45 to +45 kW)
    p_brake_mech_kw: float    # Mechanical friction braking dissipation [kW] (>= 0)
    ice_on: bool              # ICE binary On/Off state
    mode: str                 # Operational mode descriptor string
    info: Optional[Dict[str, Any]] = None # Optional telemetry/diagnostics dictionary


class BaseEMS(ABC):
    """
    Abstract interface for all parallel hybrid vehicle Energy Management Systems.
    Subclasses must implement the `decide_power_split` method.
    """

    def __init__(self, name: str, description: str):
        self.name = name
        self.description = description

    @abstractmethod
    def decide_power_split(
        self,
        ems_input: EMSInput,
        vehicle: VehicleConfig,
    ) -> EMSOutput:
        """
        Calculates the power split between ICE, EM, and Friction Brakes.

        Parameters
        ----------
        ems_input : EMSInput
            Current dynamic state of the vehicle at time t.
        vehicle : VehicleConfig
            Physical vehicle parameters and component limits.

        Returns
        -------
        EMSOutput
            Power commands and powertrain operational mode.
        """
        pass

    def reset(self) -> None:
        """Optional hook to reset internal state between drive cycles."""
        pass
